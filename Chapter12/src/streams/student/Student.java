package streams.student;

public class Student {
	private String name;
	private int score;
	
	//setter, getter
	
	//set
	public Student(String name, int score) {
		this.name=name;
		this.score=score;
		
	}
	
	//get
	public String getName() {
		return name;
		
	}
	public int getScore() {
		return score;
		
	}

}
